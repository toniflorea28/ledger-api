package com.toniflorea.ledger.domain.error;

public enum ErrorCode {
	MALFORMED_REQUEST(Kind.MALFORMED),
	IDEMPOTENCY_KEY_MISSING(Kind.MALFORMED),
	IDEMPOTENCY_KEY_REUSED(Kind.CONFLICT),
	NOT_FOUND(Kind.NOT_FOUND),
	INVALID_CURRENCY_CODE(Kind.VALIDATION),
	UNSUPPORTED_CURRENCY(Kind.VALIDATION),
	INVALID_AMOUNT(Kind.VALIDATION),
	NON_POSITIVE_AMOUNT(Kind.VALIDATION),
	SCALE_EXCEEDED(Kind.VALIDATION),
	TOO_FEW_ENTRIES(Kind.VALIDATION),
	UNKNOWN_ACCOUNT(Kind.VALIDATION),
	CURRENCY_MISMATCH(Kind.VALIDATION),
	UNBALANCED(Kind.VALIDATION),
	OVERDRAFT_EXCEEDED(Kind.VALIDATION),
	ALREADY_REVERSED(Kind.CONFLICT),
	CANNOT_REVERSE_REVERSAL(Kind.CONFLICT);

	public enum Kind {
		MALFORMED, VALIDATION, CONFLICT, NOT_FOUND
	}

	private final Kind kind;

	ErrorCode(Kind kind) {
		this.kind = kind;
	}

	public Kind kind() {
		return kind;
	}
}
